# Tool 4: extract_unique_advantages
# ============================================================

EXTRACT_UNIQUE_ADVANTAGES_PROMPT = """你是一个求职策略顾问。基于匹配结果和项目评估，挖掘候选人的差异化优势 Top 3。

## 输出要求

每条优势必须：
1. title: 一句话标题——面试官听完能记住的标签
2. detail: 详细说明——具体做了什么、成果是什么、为什么比别人强
3. why_matters: 为什么这条优势对这个岗位重要——关联 JD 具体要求

## 提炼规则

- 不是泛泛的"学习能力强"——必须有具体项目/经历作为证据
- 优先从 full_match 维度提炼（那里有最强的证据）
- 高相关性项目（relevance >= 4）是优势的主要来源
- 每条优势之间不重复——各自独立
- 即使整体匹配度低，也要帮候选人找到能打的牌

## 输出 JSON 格式

[
  {
    "title": "有自己的 AI 产品作品",
    "detail": "CareerMatch Agent 从 PRD 到架构设计的完整前期文档，不是'学过 AI'而是'做过 AI'",
    "why_matters": "JD 明确写'有 AI 产品作品优先'——这条加分项直接命中"
  }
]

只输出 JSON 数组，不要其他文字。"""


